def inject_data():
    vocab_path = os.path.join(os.path.dirname(os.path.dirname(__file__)), "data", "korean_vocab.json")
    with open(vocab_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    colloc_count = 0
    antonym_count = 0

    for book in data.get("books", []):
        for lesson in book.get("lessons", []):
            for word in lesson.get("words", []):
                kr = word.get("korean", "").strip()

                # 精确匹配与去空格匹配
                matched_colloc = COLLOCATIONS_DATA.get(kr)
                if not matched_colloc:
                    for k, v in COLLOCATIONS_DATA.items():
                        if kr == k or kr.startswith(k) or (len(k) >= 2 and k in kr):
                            matched_colloc = v
                            break

                if matched_colloc:
                    word["collocations"] = matched_colloc
                    colloc_count += 1
                elif "collocations" not in word and "collocation" in word:
                    c_str = word.pop("collocation")
                    if c_str:
                        word["collocations"] = [{"kr": c_str, "cn": ""}]
                        colloc_count += 1

                # 注入反义词
                matched_antonym = ANTONYMS_DATA.get(kr)
                if not matched_antonym:
                    for k, v in ANTONYMS_DATA.items():
                        if kr == k:
                            matched_antonym = v
                            break

                if matched_antonym:
                    word["antonyms"] = [matched_antonym]
                    antonym_count += 1

    with open(vocab_path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print(f"✓ 成功注入搭配语块: {colloc_count} 处")
    print(f"✓ 成功注入反义词对照: {antonym_count} 处")


if __name__ == "__main__":
    inject_data()
